#!/bin/bash
set -e

# Usage: sync-codeowners.sh <config_file>
# Reads devops.owners from config/access.yml and writes .github/CODEOWNERS.
CONFIG="${1:?Usage: sync-codeowners.sh <config_file>}"

command -v yq >/dev/null 2>&1 || { echo "yq is required"; exit 1; }

echo "Syncing .github/CODEOWNERS from $CONFIG..."

devops_aliases=$(yq e '.devops.owners[]' "$CONFIG" 2>/dev/null || true)

if [ -z "$devops_aliases" ]; then
  echo "No devops.owners found in $CONFIG, skipping"
  exit 0
fi

owners=""
for alias in $devops_aliases; do
  github_username=$(yq e ".users.$alias.github" "$CONFIG")
  owners="$owners @$github_username"
done

cat > .github/CODEOWNERS <<EOF
# Auto-generated by CI from config/access.yml — do not edit manually.
# Only users in devops.owners can approve and merge PRs in this repo.
*$owners
EOF

echo "Done. CODEOWNERS:"
cat .github/CODEOWNERS
